// Writes supabase/seed.sql from the demo data in src/logic/seed.js.
// Dates are shifted so the demo looks current on the day you run it:
//   npm run gen:seed               (anchor on today)
//   npm run gen:seed -- 2026-11-01 (anchor on a given date)
import fs from 'node:fs';
import { seedState } from '../src/logic/seed.js';
import { COLLECTIONS, MAPS, SETTINGS_TABLE, SETTINGS_KEYS } from '../src/lib/store.tables.js';
import { todayIso } from '../src/logic/helpers.js';

const day = process.argv[2] || todayIso();
const s = seedState(day);
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";
const rows = (table, list) => list.length
  ? `insert into public.${table} (id, ord, data) values\n` + list.map((r, i) => `  (${q(r.id)}, ${i}, ${q(JSON.stringify(r.data))}::jsonb)`).join(',\n') + `\non conflict (id) do update set ord = excluded.ord, data = excluded.data;\n`
  : '';

let out = `-- LettuBoost Ops demo data, generated by scripts/gen-seed-sql.mjs (dates anchored on ${day}).\n-- Run after schema.sql. Safe to re-run: rows are upserted by id.\n\nbegin;\n\n`;
for (const [key, table] of Object.entries(COLLECTIONS)) out += rows(table, s[key].map(x => ({ id: x.id, data: x }))) + '\n';
for (const [key, table] of Object.entries(MAPS)) out += rows(table, Object.keys(s[key]).map(id => ({ id, data: s[key][id] }))) + '\n';
out += rows(SETTINGS_TABLE, SETTINGS_KEYS.map(k => ({ id: k, data: s[k] })));
out += '\ncommit;\n';
fs.writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out);
console.log('Wrote supabase/seed.sql');
